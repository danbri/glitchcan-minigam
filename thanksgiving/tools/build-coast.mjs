// build-coast.mjs — make thanksgiving/coast-data.js from Natural Earth land polygons.
// Run: node thanksgiving/tools/build-coast.mjs <ne_50m_land.geojson> <ne_10m_land.geojson>
// Source: Natural Earth (public domain), https://github.com/nvkelso/natural-earth-vector/tree/master/geojson
// Output: SVG path strings in the page's projection (see PROJ below). Notes: docs/thanksgiving-timeline-20261104.md
import fs from 'node:fs';
import path from 'node:path';

const [coarseFile, fineFile] = process.argv.slice(2);
if (!coarseFile || !fineFile) { console.error('usage: build-coast.mjs ne_50m_land.geojson ne_10m_land.geojson'); process.exit(1); }

// Projection: equirectangular, longitude scaled by cos(45°). Must match PROJ in thanksgiving.html.
const PROJ = { lon0: -78, lat0: 58, k: 100, c: Math.cos(45 * Math.PI / 180) };
const px = (lon) => (lon - PROJ.lon0) * PROJ.k * PROJ.c;
const py = (lat) => (PROJ.lat0 - lat) * PROJ.k;

const LAYERS = [
  { name: 'coarse', file: coarseFile, bbox: [-78, 35, 6, 58], tol: 2.5 },
  { name: 'fine', file: fineFile, bbox: [-78, 37, -66, 46], tol: 0.3 },
];

// Sutherland–Hodgman clip of one ring against an axis-aligned box (lon/lat).
function clipRing(ring, [x0, y0, x1, y1]) {
  const edges = [
    [p => p[0] >= x0, (a, b) => { const t = (x0 - a[0]) / (b[0] - a[0]); return [x0, a[1] + t * (b[1] - a[1])]; }],
    [p => p[0] <= x1, (a, b) => { const t = (x1 - a[0]) / (b[0] - a[0]); return [x1, a[1] + t * (b[1] - a[1])]; }],
    [p => p[1] >= y0, (a, b) => { const t = (y0 - a[1]) / (b[1] - a[1]); return [a[0] + t * (b[0] - a[0]), y0]; }],
    [p => p[1] <= y1, (a, b) => { const t = (y1 - a[1]) / (b[1] - a[1]); return [a[0] + t * (b[0] - a[0]), y1]; }],
  ];
  let out = ring;
  for (const [inside, cut] of edges) {
    const input = out; out = [];
    if (!input.length) break;
    let prev = input[input.length - 1];
    for (const cur of input) {
      if (inside(cur)) { if (!inside(prev)) out.push(cut(prev, cur)); out.push(cur); }
      else if (inside(prev)) out.push(cut(prev, cur));
      prev = cur;
    }
  }
  return out;
}

// Douglas–Peucker on a closed ring: split it in two halves, because a ring's first and last
// points are the same point and the base line would have zero length.
function simplifyRing(pts, tol) {
  const h = Math.floor(pts.length / 2);
  return simplify(pts.slice(0, h + 1), tol).slice(0, -1).concat(simplify(pts.slice(h), tol));
}

function simplify(pts, tol) {
  if (pts.length < 4) return pts;
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [ax, ay] = pts[a], [bx, by] = pts[b];
    const dx = bx - ax, dy = by - ay, len = Math.hypot(dx, dy) || 1;
    let best = -1, bestD = tol;
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs(dy * (pts[i][0] - ax) - dx * (pts[i][1] - ay)) / len;
      if (d > bestD) { bestD = d; best = i; }
    }
    if (best > 0) { keep[best] = 1; stack.push([a, best], [best, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}

const out = {};
for (const L of LAYERS) {
  const gj = JSON.parse(fs.readFileSync(L.file, 'utf8'));
  const parts = [];
  for (const f of gj.features) {
    const g = f.geometry;
    const polys = g.type === 'Polygon' ? [g.coordinates] : g.type === 'MultiPolygon' ? g.coordinates : [];
    for (const poly of polys) {
      const ring = clipRing(poly[0], L.bbox); // outer rings only: lakes are not drawn
      if (ring.length < 3) continue;
      const p = simplifyRing(ring.map(([lon, lat]) => [px(lon), py(lat)]), L.tol);
      if (p.length < 3) continue;
      parts.push('M' + p.map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`).join('L') + 'Z');
    }
  }
  out[L.name] = parts.join('');
  console.log(L.name, parts.length, 'rings', out[L.name].length, 'chars');
}

const dest = path.join(path.dirname(new URL(import.meta.url).pathname), '..', 'coast-data.js');
fs.writeFileSync(dest,
  '// Generated by thanksgiving/tools/build-coast.mjs from Natural Earth land (public domain). Do not edit.\n' +
  `export const PROJ = ${JSON.stringify(PROJ)};\n` +
  `export const COARSE = ${JSON.stringify(out.coarse)};\n` +
  `export const FINE = ${JSON.stringify(out.fine)};\n`);
console.log('wrote', dest);
