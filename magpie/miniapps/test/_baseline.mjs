import { chromium } from 'playwright';
import { readFileSync } from 'node:fs';
import { serve } from './serve.mjs';
const s = await serve(0);
const axe = readFileSync(new URL('../node_modules/axe-core/axe.min.js', import.meta.url), 'utf8');
const b = await chromium.launch({ headless: true, executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--no-sandbox'] });
const p = await b.newPage({ viewport: { width: 390, height: 844 } });
await p.goto(s.url + '/magpie/miniapps/index.html');
await p.waitForTimeout(2000);
await p.addScriptTag({ content: axe });
const r = await p.evaluate(() => axe.run(document, { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa', 'wcag22aa', 'best-practice'] } }));
for (const v of r.violations) console.log(v.impact, v.id, v.nodes.length, '-', v.help);
const small = await p.evaluate(() => [...document.querySelectorAll('button,a,input')].filter(e => { const r = e.getBoundingClientRect(); return r.width && (r.width < 44 || r.height < 44); }).map(e => `${e.tagName}#${e.id || ''} ${Math.round(e.getBoundingClientRect().width)}x${Math.round(e.getBoundingClientRect().height)}`));
console.log('targets under 44px:', small.join(', '));
await b.close(); await s.close();
