// emit-ontology.mjs — write the edot ontology to docs/edot/ontology.ttl as RDF
// (Turtle): entity classes + subclassing, formats, and widget→type bindings.
// Commands carry their own appliesTo at runtime; a snapshot of the static schema
// lives here for tooling/reference. Re-run after editing js/ontology.js.
//   node magpie/edot/tools/emit-ontology.mjs
import { writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { toTurtle, WIDGETS, COLLECTIONS, PROVIDERS } from '../js/ontology.js';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const out = path.join(REPO, 'docs/edot');
await mkdir(out, { recursive: true });
const ttl = '# edot ontology — generated by magpie/edot/tools/emit-ontology.mjs\n'
  + '# Entity types, serialization formats, and widget→type bindings.\n'
  + '# Commands declare edot:appliesTo at runtime via the command registry.\n\n'
  + toTurtle({ widgets: WIDGETS, collections: COLLECTIONS, providers: PROVIDERS });
await writeFile(path.join(out, 'ontology.ttl'), ttl);
console.log(`Wrote docs/edot/ontology.ttl (${ttl.split('\n').length} lines).`);
