// test-inventory.mjs — record the suite's unit-test coverage from ground truth.
// Scans every test-*.mjs, extracts each ok('<assertion>', …) label (the de-facto
// spec each suite enforces), and writes a coverage record:
//   docs/edot/test-coverage.md   (human)   +   docs/edot/test-coverage.json (machine)
// Reproducible — re-run after adding tests. No deps, no browser.
//
//   node magpie/edot/tools/test-inventory.mjs
import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const EDOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const REPO = path.resolve(EDOT, '../..');

async function findTests(dir) {
  const out = [];
  for (const ent of await readdir(dir, { withFileTypes: true })) {
    if (ent.name === 'node_modules' || ent.name.startsWith('.')) continue;
    const p = path.join(dir, ent.name);
    if (ent.isDirectory()) out.push(...await findTests(p));
    else if (/^test-.*\.mjs$/.test(ent.name)) out.push(p);
  }
  return out;
}

// Extract the first string literal argument of each ok(...) call.
function extractAssertions(src) {
  const out = [];
  const re = /\bok\(\s*(['"`])((?:\\.|(?!\1)[^\\])*)\1/g;
  let m;
  while ((m = re.exec(src))) out.push(m[2].replace(/\\(['"`])/g, '$1'));
  return out;
}

// Map a test file to the app/area it belongs to.
function areaOf(rel) {
  const parts = rel.split('/');
  const i = parts.indexOf('edot');
  const seg = parts[i + 1];
  if (seg && seg.endsWith('.mjs')) {
    // top-level test-*.mjs at edot root
    if (/shell|workspace/.test(seg)) return 'shell';
    if (/editor|edot|e2e|mobile/.test(seg)) return 'editor';
    if (/kernel|object|data/.test(seg)) return 'kernel/data';
    return 'core';
  }
  return seg;
}

const files = (await findTests(EDOT)).sort();
const suites = [];
let total = 0;
for (const f of files) {
  const src = await readFile(f, 'utf8');
  const assertions = extractAssertions(src);
  const rel = path.relative(REPO, f);
  suites.push({ file: rel, area: areaOf(rel), count: assertions.length, assertions });
  total += assertions.length;
}

// Group by area.
const byArea = new Map();
for (const s of suites) {
  if (!byArea.has(s.area)) byArea.set(s.area, []);
  byArea.get(s.area).push(s);
}

const outDir = path.join(REPO, 'docs/edot');
await mkdir(outDir, { recursive: true });
await writeFile(path.join(outDir, 'test-coverage.json'), JSON.stringify({ total, suites: suites.length, areas: [...byArea.keys()], detail: suites }, null, 2));

let md = `# edot — Unit Test Coverage (generated)\n\n`;
md += `_Generated by \`magpie/edot/tools/test-inventory.mjs\` from the test sources — re-run after adding tests._\n\n`;
md += `**${total} assertions across ${suites.length} suites.** Each line is a behavior the suite enforces.\n\n`;
md += `| Area | Suites | Assertions |\n|------|-------:|-----------:|\n`;
for (const [area, ss] of [...byArea].sort()) md += `| ${area} | ${ss.length} | ${ss.reduce((n, s) => n + s.count, 0)} |\n`;
md += `\n---\n\n`;
for (const [area, ss] of [...byArea].sort()) {
  md += `## ${area}\n\n`;
  for (const s of ss.sort((a, b) => a.file.localeCompare(b.file))) {
    md += `### \`${s.file}\` — ${s.count} assertions\n\n`;
    for (const a of s.assertions) md += `- ${a}\n`;
    md += `\n`;
  }
}
await writeFile(path.join(outDir, 'test-coverage.md'), md);
console.log(`Wrote docs/edot/test-coverage.{md,json}: ${total} assertions, ${suites.length} suites, ${byArea.size} areas.`);
