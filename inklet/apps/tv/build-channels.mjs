#!/usr/bin/env node
// Regenerate channels.js from the tape library on disk.
//
//   node inklet/apps/tv/build-channels.mjs
//
// A static host has no directory listing, so the list has to be baked.
// Station names come from the filename convention documented in
// magpie/robbin/audio/README.md (per-station files are named after their
// station, with the track title trailing).

import { readdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..', '..');
const audio = join(root, 'magpie', 'robbin', 'audio');
const rel = '../../../magpie/robbin/audio';

const title = (slug) => slug.replace(/-/g, ' ').replace(/\b\w/g, c => c.toUpperCase());

const chans = [];
for (const [dir, tag] of [['per-station', 'station'], ['generic', 'rotation']]) {
  const files = (await readdir(join(audio, dir))).filter(f => f.endsWith('.mp3')).sort();
  for (const f of files) {
    const slug = f.replace(/\.mp3$/, '');
    chans.push({ id: `${dir}/${slug}`, name: title(slug), tag, url: `${rel}/${dir}/${f}` });
  }
}
// the two core tracks live at the top of the library
for (const f of (await readdir(audio)).filter(f => f.endsWith('.mp3')).sort()) {
  const slug = f.replace(/\.mp3$/, '');
  chans.unshift({ id: slug, name: title(slug), tag: 'core', url: `${rel}/${f}` });
}

await writeFile(join(here, 'channels.js'),
  `// GENERATED by build-channels.mjs — do not edit by hand.\n` +
  `// Source: magpie/robbin/audio/ (${chans.length} tracks)\n` +
  `export const CHANNELS = ${JSON.stringify(chans, null, 2)};\n`);
console.log(`channels.js: ${chans.length} channels`);
